-- ============================================================
-- edu_survey_questions에 평점형 문항의 1점/5점 기준 라벨 추가
-- (예: "매우 그렇지 않다" ~ "매우 그렇다") — 두 값 모두 nullable,
-- 서술형 문항이나 라벨을 아직 정하지 않은 평점형 문항은 비워둘 수 있다.
-- ============================================================
ALTER TABLE public.edu_survey_questions
  ADD COLUMN scale_min_label text,
  ADD COLUMN scale_max_label text;

-- 기존 평점형 문항 4종에 대한 기본 라벨 백필 (전부 동의 진술문이라 동일한 척도 사용)
UPDATE public.edu_survey_questions
SET scale_min_label = '매우 그렇지 않다', scale_max_label = '매우 그렇다'
WHERE type = 'rating' AND label IN (
  '[교육 효과성] 교육 내용은 수행하고 있는 업무(향후 업무포함) 또는 자기개발과 관련하여 교육효과가 높을 것으로 기대한다.',
  '[교과목 구성] 교과목 구성은 교육목표 달성에 전반적으로 적합하다.',
  '[교육 난이도] 교육의 난이도는 교육내용을 이해하는데 적절하다.',
  '[교육방법] 교육방법(대면교육/비대면교육/이러닝/혼합교육(집합+이러닝))은 교육내용을 이해하는데 적합하다.'
);
